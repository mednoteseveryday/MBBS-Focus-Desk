create table if not exists public.study_sessions (
 id bigint generated by default as identity primary key,
 user_id uuid not null references auth.users(id) on delete cascade,
 study_date date not null default current_date,
 subject text not null,
 topic text not null default '',
 minutes integer not null check (minutes > 0 and minutes <= 100),
 rating integer not null check (rating between 1 and 5),
 slips integer not null default 0 check (slips >= 0),
 created_at timestamptz not null default now()
);
create table if not exists public.study_tasks (
 id bigint generated by default as identity primary key,
 user_id uuid not null references auth.users(id) on delete cascade,
 title text not null,
 done boolean not null default false,
 created_at timestamptz not null default now()
);
alter table public.study_sessions enable row level security;
alter table public.study_tasks enable row level security;
create policy "Users manage own sessions" on public.study_sessions
 for all using (auth.uid() = user_id) with check (auth.uid() = user_id);
create policy "Users manage own tasks" on public.study_tasks
 for all using (auth.uid() = user_id) with check (auth.uid() = user_id);
